RATING_FIELDS = ["anonymous_id",*(f"AQ{i}" for i in range(1,7)),*(f"AQ{i}_rationale" for i in range(1,7)),"reviewer","reviewed_at","rating_minutes"]
LEDGER_FIELDS = ["anonymous_id","candidate_id","claim_text","occurrences","model_claim_type",
    "candidate_source_ids","candidate_evidence_locations","decision_critical","atomic_reviewed",
    "duplicate_of","human_claim_type","support_verdict","correct_assumption","high_impact",
    "human_evidence_locations","rationale","reviewer","reviewed_at"]
COVERAGE_FIELDS = ["anonymous_id","all_sections_and_financial_rows_checked","atomization_and_dedup_complete",
    "ledger_complete","reviewer","reviewed_at","claim_audit_minutes","notes"]


def scrub_text(text, identities):
    value = str(text)
    # Remove generated identity/header lines, HTML comments and run resource headers.
    value = re.sub(r"<!--.*?-->","",value,flags=re.S)
    value = re.sub(r"(?im)^\s*(?:[#>*-]+\s*)?(?:run[_ -]?id|provider|model(?:[_ -]?name)?|condition|arm|workflow[_ -]?version|elapsed(?:[_ -]?seconds)?|token[_ -]?usage|generated by)\s*[:=].*$","",value)
    for identity in sorted({s for s in identities if isinstance(s,str) and len(s)>2},key=len,reverse=True):
        value = re.sub(re.escape(identity),"[identity removed]",value,flags=re.I)
    value = re.sub(r"\b[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\b","[identity removed]",value,flags=re.I)
    return value


def final_artifact(reduced):
    result = reduced["result"] or {}
    ref = result.get("scorable_artifact_ref")
    if ref:
        item = reduced["artifacts"].get(ref["artifact_id"])
        if not item or item["artifact_ref"] != ref:
            raise ValueError("scorable artifact reference/hash mismatch")
        if canonical_hash(item["artifact"]) != ref["sha256"]:
            raise ValueError("scorable artifact content changed")
        return item["artifact"]
    return None


def render_output(artifact, packet, identities):
    payload = artifact["payload"]
    lines = ["# "+str(payload.get("title","Business proposal"))]
    for field in PROPOSAL_SECTION_FIELD_NAMES:
        section = payload.get(field)
        if not isinstance(section,dict):
            continue
        lines.extend(["## "+section.get("title",field),section.get("content",""),
            f"Confidence: {section.get('confidence','missing')}; reason: {section.get('confidence_reason','missing')}"])
        if section.get("key_claims"):
            lines.append("Declared claims and premises:")
        for claim in section.get("key_claims",[]):
            sources = " ".join(f"[{s}]" for s in claim.get("source_ids",[]))
            lines.append(f"- {claim.get('claim_text','')} {sources} (label: {claim.get('claim_type','')}; support proposed by author: {claim.get('source_support','')}; confidence: {claim.get('confidence','')})")
            for key in ("premise","confidence_reason"):
                if claim.get(key):
                    lines.append(f"  {key}: {claim[key]}")
        if section.get("financial_values"):
            lines.extend(["| Value | Amount | Unit | Currency | Period | Origin | Inputs | Formula |", "|---|---:|---|---|---|---|---|---|"])
            for v in section["financial_values"]:
                lines.append("| "+" | ".join(str(v.get(k,"") if v.get(k) is not None else v.get("reason","not_applicable")) for k in
                    ("value_id","value","unit","currency","period","origin","input_ids","formula_id"))+" |")
    lines.append("## Frozen references")
    for source in packet["sources"]:
        lines.append(f"[{source['source_id']}] {source['title']} — {source.get('url') or 'local frozen reference'}")
    return scrub_text("\n\n".join(lines)+"\n",identities)


def candidate_claims(artifact, identities):
    candidates = {}
    def add(text,location,kind="",sources=None,anchors=None):
        text = scrub_text(text,identities).strip()
        if not text:
            return
        key = text  # Exact-text collection only; semantic dedup still belongs to reviewer.
        if key not in candidates:
            candidates[key] = dict(claim_text=text,occurrences=[],model_claim_type=[],candidate_source_ids=[],candidate_evidence_locations=[])
        c = candidates[key]
        c["occurrences"].append(location)
        if kind and kind not in c["model_claim_type"]:
            c["model_claim_type"].append(kind)
        c["candidate_source_ids"] = sorted(set(c["candidate_source_ids"])|set(sources or []))
        c["candidate_evidence_locations"].extend(anchors or [])
    for field in PROPOSAL_SECTION_FIELD_NAMES:
        section = artifact["payload"].get(field,{})
        for index,text in enumerate(re.split(r"\n+|(?<=[。！？!?])\s*|(?<=\.)\s+(?=[A-Z])",section.get("content","")),1):
            add(text,f"{field}.content.segment{index}")
        for index,claim in enumerate(section.get("key_claims",[]),1):
            add(claim.get("claim_text",""),f"{field}.key_claims[{index}]",claim.get("claim_type",""),
                claim.get("source_ids"),claim.get("source_anchors"))
            if claim.get("premise"):
                add(claim["premise"],f"{field}.key_claims[{index}].premise")
        for index,value in enumerate(section.get("financial_values",[]),1):
            add(json.dumps(value,ensure_ascii=False,sort_keys=True),f"{field}.financial_values[{index}]",value.get("origin",""),value.get("source_ids"))
    return [dict(candidate_id=f"C{i:04d}",**c) for i,c in enumerate(candidates.values(),1)]


def build_blind_pack(experiment, output, *, seed=20260906):
    experiment,output = Path(experiment),Path(output)
    plan = load_plan(experiment)
    canonical = []
    for row in status(experiment)["rows"]:
        if not row["run_path"]:
            continue
        reduced = reduce_run(contained(experiment,row["run_path"]),condition=row["condition"])
        artifact = final_artifact(reduced)
        if artifact is None:
            continue
        packet = read_json(Path(plan["case_root"])/"cases"/row["case_id"]/"packet.json")
        config = reduced["config"]
        identities = [row["run_id"],row["planned_id"],config.get("model_exact_id"),config.get("model_config_version"),
            "Gemini 2.5 Flash","gemini-2.5-flash","Granite H Micro","granite-h-micro-32k", "granite-4.0-h-micro",
            "synthetic-contract-provider", "s4-synthetic-only"]
        canonical.append(dict(row=row,reduced=reduced,artifact=artifact,packet=packet,identities=identities))
    output.mkdir(parents=True,exist_ok=False)
    public,private = output/"reviewer",output/"private"
    public.mkdir()
    private.mkdir()
    (public/"outputs").mkdir()
    (public/"evidence").mkdir()
    rng = random.Random(seed)
    rng.shuffle(canonical)
    repeats = max(1,int(len(canonical)*.2+.5)) if canonical else 0
    entries = [(i,False) for i in range(len(canonical))]+[(i,True) for i in rng.sample(range(len(canonical)),repeats)]
    rng.shuffle(entries)
    # IDs/order do not encode condition/case or which copy is a repeat.
    mapping,rating_rows,ledger,coverage = [],[],[],[]
    originals = {}
    for index,(source_index,is_repeat) in enumerate(entries,1):
        anon = f"P{index:03d}"
        record = canonical[source_index]
        text = render_output(record["artifact"],record["packet"],record["identities"])
        (public/"outputs"/f"{anon}.md").write_text(text,encoding="utf-8")
        mapping.append(dict(anonymous_id=anon,source_index=source_index,hidden_repeat=is_repeat,
            run_id=record["row"]["run_id"],planned_id=record["row"]["planned_id"],
            case_id=record["row"]["case_id"],condition=record["row"]["condition"],
            execution=record["row"]["execution"],source_event_sha256=record["reduced"]["event_sha256"],
            anonymous_sha256=file_hash(public/"outputs"/f"{anon}.md")))
        rating_rows.append(dict.fromkeys(RATING_FIELDS,""))
        rating_rows[-1]["anonymous_id"] = anon
        if not is_repeat:
            originals[source_index] = anon
        # Same per-copy extraction/coverage for every visible ID avoids exposing repeats.
        # The hidden mapping ensures only the original is used in canonical metrics.
        if not is_repeat:
            for candidate in candidate_claims(record["artifact"],record["identities"]):
                ledger.append({**dict.fromkeys(LEDGER_FIELDS,""),"anonymous_id":anon,**candidate})
            coverage.append({**dict.fromkeys(COVERAGE_FIELDS,""),"anonymous_id":anon})
    for row in mapping:
        row["canonical_anonymous_id"] = originals[row["source_index"]]
    # Shared evidence has only frozen source IDs/contents, no run or condition identity.
    sources = {}
    for record in canonical:
        for source in record["packet"]["sources"]:
            sid = source["source_id"]
            text = contained(Path(plan["case_root"]),source["txt_path"]).read_text(encoding="utf-8")
            if sid in sources and sources[sid] != text:
                raise ValueError("source ID collision across cases")
            sources[sid] = text
            # Validate ID before using it as a filename.
            if not re.fullmatch(r"[A-Za-z0-9_.-]+",sid):
                raise ValueError("unsafe frozen source identifier")
            (public/"evidence"/f"{sid}.txt").write_text(text,encoding="utf-8")
    write_csv(public/"ratings.csv",rating_rows,RATING_FIELDS)
    # Release only AFTER ratings: fewer Gold copies would otherwise reveal repeats.
    write_csv(private/"gold_ledger_candidates.csv",ledger,LEDGER_FIELDS)
    write_csv(private/"coverage_candidates.csv",coverage,COVERAGE_FIELDS)
    shutil.copyfile(Path(plan["case_root"])/"EVALUATION_RUBRIC.md",public/"RUBRIC.md")
    guide = """# Human review instructions

Read one anonymous proposal at a time. Complete the six dimensions (integer 1–5),
each rationale, reviewer and date in ratings.csv. Do not compare adjacent outputs.
Use the frozen rubric formula (the documented Example A correction is 88.75).
Record rating/audit minutes; these are workflow planning records, not paper outcomes.

Gold review is a second phase after ratings. The coordinator provides unique final
outputs for a single shared ledger audit; hidden rating repeats are not new runs or
additional Gold audits. All visible candidate rows are initially UNJUDGED.

Review every section, its prose, declared claims, premises and financial rows. The
extractor is only a locator. Add omitted material statements; split compound claims
into atomic rows. Mark decision_critical yes/no and atomic_reviewed yes. For semantic
duplicates within the SAME output, set duplicate_of to its candidate ID and preserve
all locations. Never merge different outputs. State human_claim_type as factual,
assumption, recommendation or projection. support_verdict is sufficient,
partial_support, none or contradicted. Partial support is not sufficient. A verifiable
fact lacking evidence cannot become a correct assumption merely by its model label.
correct_assumption and high_impact are yes/no human judgments. Record evidence
locations, rationale, reviewer and reviewed_at. Complete coverage.csv only after all
decision-critical claims (including ones not proposed by the model) have been checked.
No claim metric is calculated before coverage and judgments are complete.

Model-proposed support, confidence and citations are content to review, not truth.
Source IDs and quotes remain visible. RAM, tokens, model/condition and run identity
are not shown. Content style/length may still make perfect architecture blinding
impossible. No external publication approval is implied by this internal packet.
"""
    (public/"GUIDE.md").write_text(guide,encoding="utf-8")
    write_csv(private/"identity_mapping.csv",mapping)
    integrity = {p.relative_to(public).as_posix():file_hash(p) for p in public.rglob("*") if p.is_file() and p.suffix != ".csv"}
    write_json(private/"integrity.json",integrity)
    audit = dict(kind=plan["kind"],canonical_outputs=len(canonical),rating_copies=len(entries),hidden_repeats=repeats,
        human_ratings_filled=0,human_gold_verdicts_filled=0,actual_model_calls=0,
        rating_phase="all copies; identities in private/ only",gold_phase="canonical copies only after ratings",
        missing_canonical_outputs=8-len(canonical))
    write_json(private/"pack_audit.json",audit)
    return audit


def _yesno(value):
    if value not in ("yes","no"):
        raise ValueError("human yes/no judgment required")
    return value == "yes"


def claim_metrics(rows, coverage):
    required = ("all_sections_and_financial_rows_checked","atomization_and_dedup_complete","ledger_complete")
    if any(coverage.get(k) != "yes" for k in required) or not coverage.get("reviewer") or not coverage.get("reviewed_at"):
        return {name:ratio(None,None,state="pending_human_review") for name in ("claim_grounding","assumption_transparency","high_impact_unsupported")}
    keys = [r["candidate_id"] for r in rows]
    if len(keys) != len(set(keys)) or not rows:
        raise ValueError("unique candidate IDs and an audited output inventory required")
    keyed = {r["candidate_id"]:r for r in rows}
    included = []
    for row in rows:
        critical = _yesno(row["decision_critical"])
        if row.get("atomic_reviewed") != "yes" or not row.get("reviewer") or not row.get("reviewed_at") or not row.get("rationale"):
            raise ValueError("atomicity and human audit provenance incomplete")
        duplicate = row.get("duplicate_of")
        if duplicate:
            if duplicate not in keyed or duplicate == row["candidate_id"] or keyed[duplicate].get("duplicate_of"):
                raise ValueError("duplicate must reference a canonical claim in the same output")
            if critical != _yesno(keyed[duplicate]["decision_critical"]):
                raise ValueError("duplicate criticality differs from canonical claim")
            continue
        if not critical:
            continue
        claim_type = row["human_claim_type"]
        if claim_type not in ("factual","assumption","recommendation","projection"):
            raise ValueError("human claim type required")
        support = row["support_verdict"]
        if support not in ("sufficient","partial_support","none","contradicted"):
            raise ValueError("human support verdict required")
        assumption, high = _yesno(row["correct_assumption"]),_yesno(row["high_impact"])
        if support in ("sufficient","partial_support","contradicted") and not row.get("human_evidence_locations"):
            raise ValueError("support judgment requires evidence location")
        proposed=row.get("model_claim_type","")
        if isinstance(proposed,str) and proposed.startswith("["):
            proposed=json.loads(proposed)
        labeled_assumption=proposed=="assumption" or isinstance(proposed,list) and "assumption" in proposed
        if assumption and (claim_type != "assumption" or support == "sufficient" or not labeled_assumption):
            raise ValueError("correct assumption requires an unsupported genuine, explicitly labeled assumption")
        included.append((support == "sufficient",assumption,high and claim_type == "factual"))
    unsupported = [r for r in included if not r[0]]
    high_factual = [r for r in included if r[2]]
    return dict(claim_grounding=ratio(sum(r[0] for r in included),len(included)),
        assumption_transparency=ratio(sum(r[1] for r in unsupported),len(unsupported)),
        high_impact_unsupported=ratio(sum(not r[0] for r in high_factual),len(high_factual)))


def import_human(pack):
    pack = Path(pack)
    public,private = pack/"reviewer",pack/"private"
    for path,digest in read_json(private/"integrity.json").items():
        if file_hash(contained(public,path)) != digest:
            raise ValueError("anonymous content/rubric/evidence changed during review")
    mapping = read_csv(private/"identity_mapping.csv")
    ratings = read_csv(public/"ratings.csv")
    coverage = read_csv(public/"coverage.csv") if (public/"coverage.csv").exists() else []
    ledger = read_csv(public/"gold_ledger.csv") if (public/"gold_ledger.csv").exists() else []
    known = {m["anonymous_id"] for m in mapping}
    def index_unique(rows):
        result = {}
        for row in rows:
            aid = row["anonymous_id"]
            if aid not in known or aid in result:
                raise ValueError("unknown/duplicate anonymous row")
            result[aid] = row
        if set(result) != known:
            raise ValueError("missing anonymous rows")
        return result
    ratings = index_unique(ratings)
    original_ids = {m["anonymous_id"] for m in mapping if m["hidden_repeat"] == "False"}
    if len({c["anonymous_id"] for c in coverage}) != len(coverage) or any(c["anonymous_id"] not in original_ids for c in coverage):
        raise ValueError("invalid canonical coverage IDs")
    coverage = {c["anonymous_id"]:c for c in coverage}
    grouped = defaultdict(list)
    for claim in ledger:
        if claim["anonymous_id"] not in known:
            raise ValueError("unknown ledger identity")
        grouped[claim["anonymous_id"]].append(claim)
    output,scores = {},{}
    for item in mapping:
        aid = item["anonymous_id"]
        rating = ratings[aid]
        fields = [rating[f"AQ{i}"] for i in range(1,7)]
        score = None
        if all(v != "" for v in fields):
            if not rating["reviewer"] or not rating["reviewed_at"] or any(not rating[f"AQ{i}_rationale"] for i in range(1,7)):
                raise ValueError("complete human rating provenance/rationales required")
            try:
                score = academic_score([int(v) for v in fields])
            except (ValueError,TypeError) as exc:
                raise ValueError("invalid human rating") from exc
        scores[aid] = score
        if item["hidden_repeat"] == "True":
            continue
        output[item["planned_id"]] = dict(academic_quality=score,
            academic_quality_state="observed" if score is not None else "pending_human_review",
            claims=claim_metrics(grouped[aid],coverage.get(aid,{})),anonymous_id=aid)
    consistency=[]
    for item in mapping:
        if item["hidden_repeat"] == "True":
            a,b=scores[item["anonymous_id"]],scores[item["canonical_anonymous_id"]]
            consistency.append(dict(anonymous_id=item["anonymous_id"],canonical_anonymous_id=item["canonical_anonymous_id"],
                absolute_score_difference=abs(a-b) if a is not None and b is not None else None,
                status="observed" if a is not None and b is not None else "pending_human_review",
                interpretation="within one rater; not independent cases or inter-rater reliability"))
    return output,consistency


def release_gold(pack):
    """One audit per canonical output, released after the blinded rating phase."""
    pack = Path(pack)
    output,consistency = import_human(pack)
    if any(row["academic_quality"] is None for row in output.values()) or any(r["status"] != "observed" for r in consistency):
        raise ValueError("finish all blinded ratings before releasing unique-output Gold ledger")
    for source,target in (("gold_ledger_candidates.csv","gold_ledger.csv"),("coverage_candidates.csv","coverage.csv")):
        destination = pack/"reviewer"/target
        with destination.open("xb") as stream:
            stream.write((pack/"private"/source).read_bytes())
    return dict(status="gold_ready",canonical_outputs=len(output),additional_model_runs=0)
