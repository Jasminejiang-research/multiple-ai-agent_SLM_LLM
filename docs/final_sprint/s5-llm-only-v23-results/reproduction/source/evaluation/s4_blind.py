"""Anonymous final-output packets and one shared HUMAN Gold Ledger.

Extraction deliberately includes prose and financial rows, not just key_claims.
Candidate rows are NOT decision-criticality/support judgments. Human coverage,
atomization, deduplication and adjudication are required before claim metrics.
"""
